"""Build the static course site from courses/*.md into _site/.

Each courses/<slug>.md has simple `key: "value"` front matter (code, title,
area, learn_url, labs_url) followed by a plain-text body.
The index page is generated by iterating the courses folder.
"""
import html
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COURSES = ROOT / "courses"
OUT = ROOT / "_site"
ASSETS = ROOT / "site_assets"

PAGE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<link rel="stylesheet" href="{root}style.css"></head>
<body><header><a href="{root}">ESI Course Catalogue</a></header>
<main>{body}</main></body></html>
"""


def parse(path):
    _, fm, body = path.read_text(encoding="utf-8").split("---", 2)
    meta = {}
    for line in fm.strip().splitlines():
        key, _, val = line.partition(":")
        val = val.strip()
        if val.startswith('"') and val.endswith('"'):
            val = val[1:-1].replace('\\"', '"').replace("\\\\", "\\")
        meta[key.strip()] = val
    meta["slug"] = path.stem
    meta["body"] = body.strip()
    return meta


def link(url, label):
    if not url:
        return ""
    return f'<li><a href="{html.escape(url)}">{label}</a></li>'


def render_body(body):
    paras = [p.strip() for p in re.split(r"\n\s*\n", body) if p.strip()]
    return "".join(f"<p>{html.escape(p)}</p>" for p in paras)


def main():
    courses = sorted((parse(p) for p in COURSES.glob("*.md")), key=lambda c: c["code"].lower())
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    if ASSETS.exists():
        for f in ASSETS.iterdir():
            shutil.copy(f, OUT / f.name)

    for c in courses:
        d = OUT / c["slug"]
        d.mkdir()
        labs = link(c.get("labs_url"), "Hands-on labs (GitHub)") or "<li>No labs for this course</li>"
        body = (
            f"<h1>{html.escape(c['title'])}</h1>"
            f"<p class='meta'>{html.escape(c['code'])} &middot; {html.escape(c['area'])}</p>"
            f"{render_body(c['body'])}<ul>{link(c.get('learn_url'), 'Course on Microsoft Learn')}{labs}</ul>"
            "<p><a href='../'>&larr; All courses</a></p>"
        )
        (d / "index.html").write_text(
            PAGE.format(title=html.escape(c["title"]), root="../", body=body), encoding="utf-8"
        )

    areas = {}
    for c in courses:
        areas.setdefault(c["area"], []).append(c)
    sections = ""
    for area in sorted(areas):
        items = "".join(
            f"<li><a href='{c['slug']}/'>{html.escape(c['title'])}</a> "
            f"<span class='code'>{html.escape(c['code'])}</span></li>"
            for c in areas[area]
        )
        sections += f"<h2>{html.escape(area)}</h2><ul class='courses'>{items}</ul>"
    (OUT / "index.html").write_text(
        PAGE.format(title="ESI Course Catalogue", root="", body="<h1>Course catalogue</h1>" + sections),
        encoding="utf-8",
    )
    (OUT / ".nojekyll").write_text("")
    print(f"Built {len(courses)} course pages into {OUT}")


if __name__ == "__main__":
    main()
